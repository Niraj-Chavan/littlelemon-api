# ---------------------------------------------------------------------------
# Environment variables: loaded from the project-root .env file so the MySQL
# password is never hardcoded in the source (slide 15 recommendation).
# ---------------------------------------------------------------------------

def load_env(path):
    """Tiny .env loader (KEY=VALUE per line) with no extra dependency."""
    if not path.exists():
        return
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip())


